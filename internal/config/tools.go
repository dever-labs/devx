package config

// Tool declares a required SDK, runtime, or CLI tool for the project.
// devx doctor checks each tool using its Check command and reports missing tools.
// devx setup (or devx doctor --fix) installs missing tools using the Install block.
type Tool struct {
	Name    string  `yaml:"name"`
	Version string  `yaml:"version,omitempty"` // required version; detected from repo files when omitted
	Check   string  `yaml:"check,omitempty"`   // shell command to verify installation; defaulted for well-known tools
	Install Install `yaml:"install,omitempty"`
	// Installer selects how a missing tool is installed: "" (auto: prefer a
	// version manager such as volta/fnm/nvm/corepack) or "system" (only use Install).
	Installer string `yaml:"installer,omitempty"`

	// Source records where Version came from; filled at runtime, not in YAML.
	Source string `yaml:"-"`
	// Conflict is set when an explicit Version differs from the repo-detected one.
	Conflict string `yaml:"-"`
}

// Install holds platform-specific install commands.
type Install struct {
	Windows string `yaml:"windows,omitempty"`
	MacOS   string `yaml:"macos,omitempty"`
	Linux   string `yaml:"linux,omitempty"`
}

// SetupStep is a host-side command run as part of `devx setup`.
// Steps run in declaration order. RunOnce steps are skipped if their
// command hash matches a previous successful run stored in .devx/setup-state.json.
type SetupStep struct {
	Name string `yaml:"name"`
	Run  string `yaml:"run,omitempty"`
	// Workspace: "auto" replaces run with a single root install for the detected
	// npm/yarn/pnpm workspace (instead of per-package installs).
	Workspace string `yaml:"workspace,omitempty"`
	Workdir   string `yaml:"workdir,omitempty"`  // working directory; defaults to cwd
	RunOnce   bool   `yaml:"runOnce,omitempty"`  // skip if hash matches last run
	Platform  string `yaml:"platform,omitempty"` // all | windows | linux | macos (default: all)
}

// EnvFile describes a local, gitignored config file generated by `devx setup`
// from a template and values sourced from env vars, prompts, or commands.
type EnvFile struct {
	File     string               `yaml:"file"`
	Template string               `yaml:"template,omitempty"` // ${KEY} placeholders; omitted = dotenv KEY=value lines
	Values   map[string]EnvSource `yaml:"values"`
}

// EnvSource says where a single value comes from.
type EnvSource struct {
	From    string `yaml:"from"`              // env | command | prompt
	Name    string `yaml:"name,omitempty"`    // env: variable name (defaults to the key)
	Run     string `yaml:"run,omitempty"`     // command: shell command whose stdout is the value
	Secret  bool   `yaml:"secret,omitempty"`  // prompt: do not echo input
	Default string `yaml:"default,omitempty"` // fallback; "generate" yields a random 32-char hex value
}
